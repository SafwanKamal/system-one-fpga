// Separate observed-profile candidate; not integrated or target deployed.
// Defaults deny all. Keep SOURCE_PATH_QUALIFIED=0 until shared MID0 paths
// (CCI-400/SMMU TCU) and metadata provenance are qualified for this endpoint.
// Accepted USER[9:0]=0 only, PROT=privileged secure data, upper USER=2000/2800.
// No guessed meanings for bits11/13; no identity comparison across AXI IDs.
// Remaining transaction, drain, reset and fairness limits match the sealed
// requester-filter engine. This module alone is not R5 source authentication.
module typed200_r5_profile_filter #(
    parameter integer ENABLE_R5=0,
    parameter integer SOURCE_PATH_QUALIFIED=0,
    parameter logic [39:0] BASE=40'h00a0000000,
    parameter logic [39:0] END_EXCLUSIVE=40'h00a0002000
) (
    input wire clk, reset_n,
    input wire [15:0] s_awid, input wire [39:0] s_awaddr,
    input wire [7:0] s_awlen, input wire [2:0] s_awsize,
    input wire [1:0] s_awburst, input wire s_awlock,
    input wire [3:0] s_awcache, input wire [2:0] s_awprot,
    input wire [3:0] s_awqos, input wire [15:0] s_awuser,
    input wire s_awvalid, output wire s_awready,
    input wire [127:0] s_wdata, input wire [15:0] s_wstrb,
    input wire s_wlast,s_wvalid, output wire s_wready,
    output wire [15:0] s_bid, output wire [1:0] s_bresp,
    output wire s_bvalid, input wire s_bready,
    input wire [15:0] s_arid, input wire [39:0] s_araddr,
    input wire [7:0] s_arlen, input wire [2:0] s_arsize,
    input wire [1:0] s_arburst, input wire s_arlock,
    input wire [3:0] s_arcache, input wire [2:0] s_arprot,
    input wire [3:0] s_arqos, input wire [15:0] s_aruser,
    input wire s_arvalid, output wire s_arready,
    output wire [15:0] s_rid, output wire [127:0] s_rdata,
    output wire [1:0] s_rresp, output wire s_rlast,s_rvalid,
    input wire s_rready,
    output wire [15:0] m_awid, output wire [39:0] m_awaddr,
    output wire [7:0] m_awlen, output wire [2:0] m_awsize,
    output wire [1:0] m_awburst, output wire m_awlock,
    output wire [3:0] m_awcache, output wire [2:0] m_awprot,
    output wire [3:0] m_awqos, output wire [15:0] m_awuser,
    output wire m_awvalid, input wire m_awready,
    output wire [127:0] m_wdata, output wire [15:0] m_wstrb,
    output wire m_wlast,m_wvalid, input wire m_wready,
    input wire [15:0] m_bid, input wire [1:0] m_bresp,
    input wire m_bvalid, output wire m_bready,
    output wire [15:0] m_arid, output wire [39:0] m_araddr,
    output wire [7:0] m_arlen, output wire [2:0] m_arsize,
    output wire [1:0] m_arburst, output wire m_arlock,
    output wire [3:0] m_arcache, output wire [2:0] m_arprot,
    output wire [3:0] m_arqos, output wire [15:0] m_aruser,
    output wire m_arvalid, input wire m_arready,
    input wire [15:0] m_rid, input wire [127:0] m_rdata,
    input wire [1:0] m_rresp, input wire m_rlast,m_rvalid,
    output wire m_rready,
    output logic protocol_fault
);
    localparam [1:0] W_WAIT=0,W_SEND=1,W_DROP=2,W_RESP=3;
    localparam [1:0] R_WAIT=0,R_ISSUE=1,R_PASS=2,R_REJECT=3;
    logic [1:0] wstate,rstate;
    logic aw_full,w_full,aw_sent,w_sent,aw_allowed;
    logic [15:0] aw_id,aw_user,first_strb,ar_id,ar_user;
    logic [39:0] aw_addr,ar_addr;
    logic [7:0] aw_len,w_left,r_left;
    logic [1:0] aw_burst,ar_burst,bresp;
    logic [3:0] aw_cache,aw_qos,ar_cache,ar_qos;
    logic [2:0] aw_prot,ar_prot;
    logic [127:0] first_data;
    logic first_last;
    function automatic allowed(input [39:0] a,input [15:0] user,
        input [2:0] prot,input [7:0] len,input [2:0] size,
        input [1:0] burst,input lock);
        // Empirical lockstep diagnostic profile, not universal R5 attributes.
        // Exactly two complete USER values; poison[10] and every unobserved
        // combination remain denied. Preserve USER unchanged downstream.
        // MID0 is shared with CCI/TCU: ENABLE_R5 alone cannot authorize it.
        // SOURCE_PATH_QUALIFIED is an integration assertion, never a proof
        // generated by this module. No software-writable bypass exists.
        allowed=ENABLE_R5 && SOURCE_PATH_QUALIFIED &&
          (user==16'h2000 || user==16'h2800) && prot==3'b001 && a>=BASE && a<END_EXCLUSIVE && a[1:0]==0 &&
          len==0 && size==3'd2 && burst<=1 && !lock;
    endfunction
    wire strobe_ok=(first_strb & ~(16'h000f << aw_addr[3:0]))==0;
    assign s_awready=reset_n && wstate==W_WAIT && !aw_full && !protocol_fault;
    assign s_wready=reset_n &&
       ((wstate==W_WAIT && !w_full && !protocol_fault) || wstate==W_DROP);
    // Continue consuming a declared rejected burst even after detecting a bad
    // WLAST. New transactions stay blocked; reset is required after a fault.
    wire drop_ready=s_wready && wstate==W_DROP;
    assign s_bid=aw_id;assign s_bresp=bresp;assign s_bvalid=reset_n && wstate==W_RESP;
    assign m_awid=aw_id;assign m_awaddr=aw_addr;assign m_awlen=0;assign m_awsize=3'd2;
    assign m_awburst=aw_burst;assign m_awlock=0;assign m_awcache=aw_cache;
    assign m_awprot=aw_prot;assign m_awqos=aw_qos;assign m_awuser=aw_user;
    assign m_awvalid=reset_n && wstate==W_SEND && !aw_sent;
    assign m_wdata=first_data;assign m_wstrb=first_strb;assign m_wlast=1;
    assign m_wvalid=reset_n && wstate==W_SEND && !w_sent;
    assign m_bready=reset_n && wstate==W_SEND && aw_sent && w_sent;
    assign s_arready=reset_n && rstate==R_WAIT && !protocol_fault;
    assign m_arid=ar_id;assign m_araddr=ar_addr;assign m_arlen=0;assign m_arsize=3'd2;
    assign m_arburst=ar_burst;assign m_arlock=0;assign m_arcache=ar_cache;
    assign m_arprot=ar_prot;assign m_arqos=ar_qos;assign m_aruser=ar_user;
    assign m_arvalid=reset_n && rstate==R_ISSUE;
    assign m_rready=reset_n && rstate==R_PASS && s_rready;
    assign s_rid=ar_id;
    assign s_rdata=rstate==R_REJECT ? 128'd0:m_rdata;
    assign s_rresp=rstate==R_REJECT ? 2'b11:
      ((m_rid!=ar_id || !m_rlast) ? 2'b10:m_rresp);
    assign s_rlast=rstate==R_REJECT ? r_left==0:1'b1;
    assign s_rvalid=reset_n && (rstate==R_REJECT || (rstate==R_PASS && m_rvalid));
    always_ff @(posedge clk) begin
      if(!reset_n) begin
        wstate<=W_WAIT;rstate<=R_WAIT;aw_full<=0;w_full<=0;aw_sent<=0;w_sent<=0;
        aw_allowed<=0;protocol_fault<=0;aw_id<=0;aw_addr<=0;aw_len<=0;aw_user<=0;
        aw_burst<=0;aw_cache<=0;aw_prot<=0;aw_qos<=0;first_data<=0;first_strb<=0;
        first_last<=0;w_left<=0;bresp<=0;ar_id<=0;ar_addr<=0;ar_user<=0;
        ar_burst<=0;ar_cache<=0;ar_prot<=0;ar_qos<=0;r_left<=0;
      end else begin
        if(s_awvalid && s_awready) begin
          aw_full<=1;aw_id<=s_awid;aw_addr<=s_awaddr;aw_len<=s_awlen;aw_user<=s_awuser;
          aw_burst<=s_awburst;aw_cache<=s_awcache;aw_prot<=s_awprot;aw_qos<=s_awqos;
          aw_allowed<=allowed(s_awaddr,s_awuser,s_awprot,s_awlen,s_awsize,s_awburst,s_awlock);
        end
        if(wstate==W_WAIT && s_wvalid && s_wready) begin
          w_full<=1;first_data<=s_wdata;first_strb<=s_wstrb;first_last<=s_wlast;
        end
        case(wstate)
          W_WAIT: if(aw_full && w_full) begin
            aw_sent<=0;w_sent<=0;
            if(aw_allowed && first_last && strobe_ok)wstate<=W_SEND;
            else begin
              bresp<=2'b11;w_full<=0;
              if(first_last!=(aw_len==0))protocol_fault<=1;
              if(aw_len==0)wstate<=W_RESP;
              else begin w_left<=aw_len;wstate<=W_DROP;end
            end
          end
          W_DROP: if(s_wvalid && drop_ready) begin
            if(s_wlast!=(w_left==1))protocol_fault<=1;
            if(w_left==1)wstate<=W_RESP;
            else w_left<=w_left-1'b1;
          end
          W_SEND: begin
            if(m_awvalid && m_awready)aw_sent<=1;
            if(m_wvalid && m_wready)w_sent<=1;
            if(m_bvalid && m_bready) begin
              bresp<=m_bid==aw_id ? m_bresp:2'b10;
              if(m_bid!=aw_id)protocol_fault<=1;
              wstate<=W_RESP;
            end
          end
          W_RESP: if(s_bready) begin aw_full<=0;w_full<=0;wstate<=W_WAIT;end
        endcase
        case(rstate)
          R_WAIT: if(s_arvalid && s_arready) begin
            ar_id<=s_arid;ar_addr<=s_araddr;ar_user<=s_aruser;
            ar_burst<=s_arburst;ar_cache<=s_arcache;ar_prot<=s_arprot;ar_qos<=s_arqos;
            r_left<=s_arlen;
            rstate<=allowed(s_araddr,s_aruser,s_arprot,s_arlen,s_arsize,s_arburst,s_arlock)
              ? R_ISSUE:R_REJECT;
          end
          R_ISSUE: if(m_arready)rstate<=R_PASS;
          R_PASS: if(m_rvalid && s_rready) begin
            if(m_rid!=ar_id || !m_rlast)protocol_fault<=1;
            rstate<=R_WAIT;
          end
          R_REJECT: if(s_rready) begin
            if(r_left==0)rstate<=R_WAIT;
            else r_left<=r_left-1'b1;
          end
        endcase
      end
    end
endmodule
