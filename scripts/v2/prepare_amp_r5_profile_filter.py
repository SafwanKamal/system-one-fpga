"""Preserve the tag milestone and create a narrow, disabled filter candidate."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'build/v2/typed200-amp-r5-profile-filter-v1'
RTL=ROOT/'rtl/v2/candidates/typed200_amp_r5_profile/typed200_r5_profile_filter.sv'
ANCHOR=ROOT/'docs/research/2026-10-17-typed200-amp-linux-tag-probe-validation.json'

def sha(p):
    with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()

def main():
    prior=json.loads(ANCHOR.read_text());records={}
    for group in ['preserved_sha256','candidate_sha256']:
        for name,digest in prior[group].items():
            assert name not in records or records[name]==digest
            records[name]=digest
    records[ANCHOR.relative_to(ROOT).as_posix()]=sha(ANCHOR)
    def check(item):
        name,digest=item;assert sha(ROOT/name)==digest,name
    with ThreadPoolExecutor(max_workers=4) as pool:list(pool.map(check,records.items()))
    BASE.mkdir(exist_ok=False);RTL.parent.mkdir(exist_ok=False)
    (BASE/'prior-validation.json').write_bytes(ANCHOR.read_bytes())
    (BASE/'preservation-before.json').write_text(json.dumps(dict(passed=True,files=len(records),
        anchor=ANCHOR.relative_to(ROOT).as_posix(),anchor_sha256=sha(ANCHOR)),indent=2)+'\n')
    old=ROOT/'rtl/v2/candidates/typed200_amp/control/typed200_requester_filter.sv'
    original=old.read_text();text=original[original.index('module typed200_requester_filter'):]
    text=text.replace('module typed200_requester_filter','module typed200_r5_profile_filter',1)
    text=text.replace('parameter integer ENABLE_R5=0,','parameter integer ENABLE_R5=0,\n    parameter integer SOURCE_PATH_QUALIFIED=0,',1)
    start=text.index('        // UG1085: source MID')
    end=text.index(' && a>=BASE',start)
    text=text[:start]+'''        // Empirical lockstep diagnostic profile, not universal R5 attributes.
        // Exactly two complete USER values; poison[10] and every unobserved
        // combination remain denied. Preserve USER unchanged downstream.
        // MID0 is shared with CCI/TCU: ENABLE_R5 alone cannot authorize it.
        // SOURCE_PATH_QUALIFIED is an integration assertion, never a proof
        // generated by this module. No software-writable bypass exists.
        allowed=ENABLE_R5 && SOURCE_PATH_QUALIFIED &&
          (user==16'h2000 || user==16'h2800) && prot==3'b001'''+text[end:]
    header='''// Separate observed-profile candidate; not integrated or target deployed.
// Defaults deny all. Keep SOURCE_PATH_QUALIFIED=0 until shared MID0 paths
// (CCI-400/SMMU TCU) and metadata provenance are qualified for this endpoint.
// Accepted USER[9:0]=0 only, PROT=privileged secure data, upper USER=2000/2800.
// No guessed meanings for bits11/13; no identity comparison across AXI IDs.
// Remaining transaction, drain, reset and fairness limits match the sealed
// requester-filter engine. This module alone is not R5 source authentication.
'''
    RTL.write_text(header+text)
    # Ensure the entire transaction engine after the policy function is intact.
    assert original.split('    wire strobe_ok=',1)[1]==text.split('    wire strobe_ok=',1)[1]
    (BASE/'candidate-origin.json').write_text(json.dumps(dict(passed=True,
        original_sha256=sha(old),candidate_sha256=sha(RTL),transport_engine_unchanged=True,
        profile_users=[8192,10240],profile_prot=1,profile_mid=0,
        source_path_qualified=False,target_deployment_admitted=False),indent=2)+'\n')
    print(f'PASS {len(records)} prior files; separate disabled observed-profile candidate')

if __name__=='__main__':main()
