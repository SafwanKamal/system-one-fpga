"""Generate KR260 pin constraints for the gate bridge from AMD's Vivado board files.

carrier board.xml: physical port -> SOM240 connector pin (+ connector pin I/O standard)
som part0_pins.xml: SOM240 connector pin -> package pin
"""
from __future__ import annotations

import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

BOARDS = Path("C:/AMDDesignTools/2025.2/Vivado/data/xhub/boards/XilinxBoardStore/boards/Xilinx")

# top-level port -> (board interface, logical port)
PORTS = {
    "a": "pl_gem2", "b": "pl_gem3",
}
LOGICAL = {
    "rxc": ("rgmii", "RXC"), "rd": ("rgmii", "RD"), "rx_ctl": ("rgmii", "RX_CTL"),
    "txc": ("rgmii", "TXC"), "td": ("rgmii", "TD"), "tx_ctl": ("rgmii", "TX_CTL"),
    "mdc": ("rgmii_mdio_mdc", "MDC"), "mdio": ("rgmii_mdio_mdc", "MDIO_I"),
    "rst_n": ("reset", "RESET"),
}


def carrier_maps(path: Path):
    root = ET.parse(path).getroot()
    iomap = {}
    for pin in root.iter("pin"):
        if pin.get("name", "").startswith("som240") and pin.get("iostandard"):
            iomap[pin.get("name")] = pin.get("iostandard")
    ports = {}
    for itf in root.iter("interface"):
        name = itf.get("name")
        for pm in itf.iter("port_map"):
            pins = {int(m.get("port_index")): m.get("component_pin") for m in pm.iter("pin_map")}
            ports[(name, pm.get("logical_port"))] = pins
    return ports, iomap


def som_locs(path: Path):
    txt = path.read_text()
    return {m.group(1): m.group(2) for m in re.finditer(r'name\s*="(som240_\d_[a-z]\d+)"\s+loc="([A-Z]+\d+)"', txt)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--rx-dv", type=float, default=1.0, help="center mode: data valid before/after each RXC edge (ns)")
    ap.add_argument("--rx-mode", choices=["edge", "center", "sdr100"], default="sdr100",
                    help="sdr100: 10/100 build, PHY RX delay on; edge/center: 1000 Mb/s variants")
    ap.add_argument("--rx-skew", type=float, default=0.5, help="edge mode: data-to-clock skew at the pins (ns)")
    args = ap.parse_args()
    ports, iostd = carrier_maps(BOARDS / "kr260_carrier/1.1/board.xml")
    locs = som_locs(BOARDS / "kr260_som/1.1/part0_pins.xml")
    lines = ["# Generated by scripts/v2/gate/gen_kr260_gate_xdc.py from the Vivado KR260 board files", ""]

    def place(port: str, conn_pin: str):
        loc = locs[conn_pin]
        std = iostd.get(conn_pin, "LVCMOS18")
        lines.append(f"set_property PACKAGE_PIN {loc} [get_ports {{{port}}}]  ;# {conn_pin}")
        lines.append(f"set_property IOSTANDARD {std} [get_ports {{{port}}}]")

    for side, itf in PORTS.items():
        for lp, (suffix, logical) in LOGICAL.items():
            pins = ports[(f"{itf}_{suffix}", logical)]
            if len(pins) == 1:
                place(f"{side}_{lp}", pins[0])
            else:
                for i, cp in sorted(pins.items()):
                    place(f"{side}_{lp}[{i}]", cp)
    place("clk25", ports[("pl_gem2_rgmii_mdio_mdc", "CLK")][0] if ("pl_gem2_rgmii_mdio_mdc", "CLK") in ports
          else "som240_1_a6")
    lines += [
        "",
        "# ---- clocks",
        "create_clock -name clk25 -period 40.000 [get_ports clk25]",
        f"create_clock -name a_rxc -period {40.0 if args.rx_mode == 'sdr100' else 8.0:.3f} [get_ports a_rxc]",
        f"create_clock -name b_rxc -period {40.0 if args.rx_mode == 'sdr100' else 8.0:.3f} [get_ports b_rxc]",
        "set_clock_groups -asynchronous -group [get_clocks -include_generated_clocks clk25] "
        "-group [get_clocks a_rxc] -group [get_clocks b_rxc]",
        "",
        f"# ---- RGMII receive ({args.rx_mode}-aligned data on both RXC edges)",
    ]
    for side in ("a", "b"):
        hp = 4.0
        if args.rx_mode == "sdr100":
            # 10/100: one nibble per RXC rising edge; with the PHY RX delay (2.0 ns) the data
            # change 2.0 +/- 0.5 ns before each rising edge.  Falling-edge IDDR samples are unused.
            P = 40.0
            ports = f"{side}_rd[*] {side}_rx_ctl"
            lines += [
                f"set_input_delay -clock {side}_rxc -max {P - 1.5:.3f} [get_ports {{{ports}}}]",
                f"set_input_delay -clock {side}_rxc -min {P - 2.5:.3f} [get_ports {{{ports}}}]",
                f"set_false_path -fall_to [get_clocks {side}_rxc] -through [get_ports {{{ports}}}]",
            ]
            continue
        if args.rx_mode == "edge":
            k = args.rx_skew
            lines += [
                f"set_input_delay -clock {side}_rxc -max {k:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_input_delay -clock {side}_rxc -min {-k:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_input_delay -clock {side}_rxc -clock_fall -max -add_delay {k:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_input_delay -clock {side}_rxc -clock_fall -min -add_delay {-k:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                # Xilinx edge-aligned DDR template, limited to paths through the RGMII inputs:
                # data launched on an edge is captured by the same (BUFG-delayed) edge.
                f"set_multicycle_path -setup -end 0 -rise_from [get_clocks {side}_rxc] -rise_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_multicycle_path -setup -end 0 -fall_from [get_clocks {side}_rxc] -fall_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_false_path -setup -fall_from [get_clocks {side}_rxc] -rise_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_false_path -setup -rise_from [get_clocks {side}_rxc] -fall_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_false_path -hold -rise_from [get_clocks {side}_rxc] -rise_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
                f"set_false_path -hold -fall_from [get_clocks {side}_rxc] -fall_to [get_clocks {side}_rxc] -through [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
            ]
            continue
        dv = args.rx_dv
        lines += [
            f"set_input_delay -clock {side}_rxc -max {hp - dv:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
            f"set_input_delay -clock {side}_rxc -min {dv:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
            f"set_input_delay -clock {side}_rxc -clock_fall -max -add_delay {hp - dv:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
            f"set_input_delay -clock {side}_rxc -clock_fall -min -add_delay {dv:.3f} [get_ports {{{side}_rd[*] {side}_rx_ctl}}]",
        ]
    lines += [
        "",
        "# ---- RGMII transmit: TXC, TD and TX_CTL all leave through ODDRE1 on the same clock",
        "# (edge-aligned; the PHY adds the TX clock delay).  Launch skew is checked in the",
        "# routed report_datasheet output rather than with output-delay constraints.",
        "set_false_path -to [get_ports {a_txc a_td[*] a_tx_ctl b_txc b_td[*] b_tx_ctl}]",
        "set_property SLEW FAST [get_ports {a_txc a_td[*] a_tx_ctl b_txc b_td[*] b_tx_ctl}]",
        "",
        "# ---- slow management pins",
        "set_false_path -to [get_ports {a_mdc a_mdio a_rst_n b_mdc b_mdio b_rst_n}]",
        "set_false_path -from [get_ports {a_mdio b_mdio}]",
        "set_property PULLUP true [get_ports {a_mdio b_mdio}]",
    ]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
